-- Zoho-style accounting foundation for Concept Cleaning Services.
-- Phase 1 only: creates an isolated double-entry ledger. No operational records are
-- auto-posted by this migration; historical reconciliation and posting rules come later.
-- Do not apply to production until reviewed and tested against the intended Supabase project.

BEGIN;

CREATE TABLE IF NOT EXISTS public.accounting_periods (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  starts_on date NOT NULL,
  ends_on date NOT NULL,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  closed_at timestamptz,
  closed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  CHECK (ends_on >= starts_on),
  CHECK ((status = 'open' AND closed_at IS NULL) OR (status = 'closed' AND closed_at IS NOT NULL)),
  UNIQUE (starts_on, ends_on)
);

CREATE TABLE IF NOT EXISTS public.accounting_accounts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  account_type text NOT NULL CHECK (account_type IN ('asset', 'liability', 'equity', 'income', 'expense')),
  parent_id uuid REFERENCES public.accounting_accounts(id) ON DELETE RESTRICT,
  description text,
  is_control_account boolean NOT NULL DEFAULT false,
  is_system_account boolean NOT NULL DEFAULT false,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE TABLE IF NOT EXISTS public.journal_entries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  entry_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  entry_date date NOT NULL DEFAULT CURRENT_DATE,
  description text NOT NULL,
  reference text,
  source_type text,
  source_id text,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'posted', 'void')),
  reversal_of uuid UNIQUE REFERENCES public.journal_entries(id) ON DELETE RESTRICT,
  period_id uuid NOT NULL REFERENCES public.accounting_periods(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  posted_at timestamptz,
  posted_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  voided_at timestamptz,
  voided_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  UNIQUE (source_type, source_id),
  CHECK ((status = 'draft' AND posted_at IS NULL AND voided_at IS NULL)
      OR (status = 'posted' AND posted_at IS NOT NULL AND voided_at IS NULL)
      OR (status = 'void' AND posted_at IS NULL AND voided_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS public.journal_lines (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  journal_entry_id uuid NOT NULL REFERENCES public.journal_entries(id) ON DELETE RESTRICT,
  line_number integer NOT NULL CHECK (line_number > 0),
  account_id uuid NOT NULL REFERENCES public.accounting_accounts(id) ON DELETE RESTRICT,
  description text,
  debit numeric(18,2) NOT NULL DEFAULT 0 CHECK (debit >= 0),
  credit numeric(18,2) NOT NULL DEFAULT 0 CHECK (credit >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (journal_entry_id, line_number),
  CHECK ((debit > 0 AND credit = 0) OR (credit > 0 AND debit = 0))
);

CREATE TABLE IF NOT EXISTS public.accounting_audit_log (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  table_name text NOT NULL,
  record_id text NOT NULL,
  action text NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
  old_values jsonb,
  new_values jsonb,
  changed_at timestamptz NOT NULL DEFAULT now(),
  changed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_accounting_periods_dates ON public.accounting_periods(starts_on, ends_on);
CREATE INDEX IF NOT EXISTS idx_accounting_accounts_type_active ON public.accounting_accounts(account_type, is_active);
CREATE INDEX IF NOT EXISTS idx_journal_entries_date_status ON public.journal_entries(entry_date, status);
CREATE INDEX IF NOT EXISTS idx_journal_entries_period ON public.journal_entries(period_id);
CREATE INDEX IF NOT EXISTS idx_journal_entries_source ON public.journal_entries(source_type, source_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_entry ON public.journal_lines(journal_entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_account ON public.journal_lines(account_id);
CREATE INDEX IF NOT EXISTS idx_accounting_audit_changed_at ON public.accounting_audit_log(changed_at DESC);

CREATE OR REPLACE FUNCTION public.accounting_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_accounting_accounts_updated_at ON public.accounting_accounts;
CREATE TRIGGER trg_accounting_accounts_updated_at
BEFORE UPDATE ON public.accounting_accounts
FOR EACH ROW EXECUTE FUNCTION public.accounting_set_updated_at();

CREATE OR REPLACE FUNCTION public.accounting_audit_row()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  old_row jsonb;
  new_row jsonb;
  record_key text;
BEGIN
  IF TG_OP <> 'INSERT' THEN old_row := to_jsonb(OLD); END IF;
  IF TG_OP <> 'DELETE' THEN new_row := to_jsonb(NEW); END IF;
  record_key := COALESCE(new_row->>'id', old_row->>'id', new_row->>'entry_number', old_row->>'entry_number', new_row->>'code', old_row->>'code');
  INSERT INTO public.accounting_audit_log(table_name, record_id, action, old_values, new_values, changed_by)
  VALUES (TG_TABLE_NAME, COALESCE(record_key, 'unknown'), TG_OP, old_row, new_row, auth.uid());
  RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS trg_accounting_accounts_audit ON public.accounting_accounts;
CREATE TRIGGER trg_accounting_accounts_audit
AFTER INSERT OR UPDATE OR DELETE ON public.accounting_accounts
FOR EACH ROW EXECUTE FUNCTION public.accounting_audit_row();

DROP TRIGGER IF EXISTS trg_accounting_periods_audit ON public.accounting_periods;
CREATE TRIGGER trg_accounting_periods_audit
AFTER INSERT OR UPDATE OR DELETE ON public.accounting_periods
FOR EACH ROW EXECUTE FUNCTION public.accounting_audit_row();

DROP TRIGGER IF EXISTS trg_journal_entries_audit ON public.journal_entries;
CREATE TRIGGER trg_journal_entries_audit
AFTER INSERT OR UPDATE OR DELETE ON public.journal_entries
FOR EACH ROW EXECUTE FUNCTION public.accounting_audit_row();

CREATE OR REPLACE FUNCTION public.accounting_guard_journal_entry()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  target_period public.accounting_periods%ROWTYPE;
  debit_total numeric(18,2);
  credit_total numeric(18,2);
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status <> 'draft' THEN
      RAISE EXCEPTION 'Only draft journal entries may be deleted';
    END IF;
    RETURN OLD;
  END IF;

  IF TG_OP = 'UPDATE' AND OLD.status <> 'draft' THEN
    RAISE EXCEPTION 'Posted or void journal entries are immutable; use a reversing journal or correction entry';
  END IF;

  IF NEW.status = 'posted' AND (TG_OP = 'INSERT' OR OLD.status <> 'posted') THEN
    SELECT * INTO target_period FROM public.accounting_periods WHERE id = NEW.period_id FOR SHARE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Accounting period does not exist'; END IF;
    IF target_period.status <> 'open' THEN RAISE EXCEPTION 'Cannot post to a closed accounting period'; END IF;
    IF NEW.entry_date < target_period.starts_on OR NEW.entry_date > target_period.ends_on THEN
      RAISE EXCEPTION 'Journal date must fall inside its accounting period';
    END IF;

    SELECT COALESCE(SUM(debit), 0), COALESCE(SUM(credit), 0)
      INTO debit_total, credit_total
      FROM public.journal_lines WHERE journal_entry_id = NEW.id;

    IF debit_total <= 0 OR debit_total <> credit_total THEN
      RAISE EXCEPTION 'Journal must have equal, non-zero total debits and credits (debits %, credits %)', debit_total, credit_total;
    END IF;

    IF EXISTS (
      SELECT 1 FROM public.journal_lines jl
      JOIN public.accounting_accounts aa ON aa.id = jl.account_id
      WHERE jl.journal_entry_id = NEW.id AND aa.is_active = false
    ) THEN
      RAISE EXCEPTION 'Journal contains an inactive account';
    END IF;
    NEW.posted_at := now();
    NEW.posted_by := auth.uid();
  END IF;

  IF NEW.status = 'void' THEN
    IF TG_OP = 'UPDATE' AND OLD.status <> 'draft' THEN
      RAISE EXCEPTION 'Only draft journal entries may be voided';
    END IF;
    NEW.voided_at := now();
    NEW.voided_by := auth.uid();
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_accounting_journal_entry_guard ON public.journal_entries;
CREATE TRIGGER trg_accounting_journal_entry_guard
BEFORE INSERT OR UPDATE OR DELETE ON public.journal_entries
FOR EACH ROW EXECUTE FUNCTION public.accounting_guard_journal_entry();

CREATE OR REPLACE FUNCTION public.accounting_guard_journal_line()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  parent_status text;
  account_active boolean;
BEGIN
  SELECT status INTO parent_status
    FROM public.journal_entries
    WHERE id = COALESCE(NEW.journal_entry_id, OLD.journal_entry_id)
    FOR SHARE;
  IF parent_status IS NULL THEN RAISE EXCEPTION 'Journal entry does not exist'; END IF;
  IF parent_status <> 'draft' THEN RAISE EXCEPTION 'Journal lines can only be changed while the journal is draft'; END IF;

  IF TG_OP <> 'DELETE' THEN
    SELECT is_active INTO account_active FROM public.accounting_accounts WHERE id = NEW.account_id;
    IF account_active IS DISTINCT FROM true THEN RAISE EXCEPTION 'Account is inactive or does not exist'; END IF;
    RETURN NEW;
  END IF;
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_accounting_journal_line_guard ON public.journal_lines;
CREATE TRIGGER trg_accounting_journal_line_guard
BEFORE INSERT OR UPDATE OR DELETE ON public.journal_lines
FOR EACH ROW EXECUTE FUNCTION public.accounting_guard_journal_line();

CREATE OR REPLACE FUNCTION public.accounting_post_journal(p_journal_id uuid)
RETURNS public.journal_entries
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  result_row public.journal_entries%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin_or_super(auth.uid()) THEN
    RAISE EXCEPTION 'Only authorized accounting administrators may post journals';
  END IF;
  UPDATE public.journal_entries SET status = 'posted'
   WHERE id = p_journal_id AND status = 'draft'
   RETURNING * INTO result_row;
  IF NOT FOUND THEN RAISE EXCEPTION 'Draft journal not found or already processed'; END IF;
  RETURN result_row;
END;
$$;

REVOKE ALL ON FUNCTION public.accounting_post_journal(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.accounting_post_journal(uuid) TO authenticated;

